#!/usr/bin/env bash
# Serves the repository's pages at http://localhost:PORT for local testing (see docs/deployment.md#local-backend).
#
#   locally-test-server.sh                 Serve the pages; they use the production backend
#   locally-test-server.sh --with-backend  Also run artifacts/newest/server.jar on port 9000 with the
#                                          settings of secrets/server.env (its database, real mail)
#   --port N                               Page port (default 8000, which the pages' CSP allows)
#
# The page configuration deployment/client/.env (git-ignored) is generated from secrets/client.env
# or its template, plus EDUSQUIRREL_BACKEND_URL with --with-backend. Everything listens on 127.0.0.1
# only, because the served repository root also contains deployment/secrets/.
# shellcheck source=SCRIPTDIR/../lib/common.sh
source "$(dirname "${BASH_SOURCE[0]}")/../lib/common.sh"
LOG_PREFIX=local

with_backend=false port=8000
while [[ $# -gt 0 ]]; do
  case "$1" in
    --with-backend) with_backend=true ;;
    --port) [[ $# -ge 2 && "$2" =~ ^[0-9]+$ ]] || die "--port needs a number"; port=$2; shift ;;
    *) die "unknown argument: $1" ;;
  esac
  shift
done
require_cmd node npx

for name in client.js worker.js; do
  [[ -f "$REPO_ROOT/artifacts/newest/$name" ]] || die "missing artifacts/newest/$name; run 'sbt buildJS' first"
done

# Regenerate only a file this script created, never a hand-written one.
marker="# Generated by deployment/client/locally-test-server.sh; edit secrets/client.env instead."
client_env="$REPO_ROOT/deployment/client/.env"
if [[ -f "$client_env" ]] && [[ "$(head -n 1 "$client_env")" != "$marker" ]]; then
  die "deployment/client/.env was not generated by this script; move it away first"
fi
source_env="$SECRETS_DIR/client.env"
[[ -f "$source_env" ]] || source_env="$SECRETS_DIR/client.env.example"
{
  printf '%s\n' "$marker"
  grep -v '^[[:space:]]*EDUSQUIRREL_BACKEND_URL=' "$source_env" || true
  if [[ "$with_backend" == true ]]; then printf 'EDUSQUIRREL_BACKEND_URL=http://localhost:9000\n'; fi
} > "$client_env"

if [[ "$with_backend" == true ]]; then
  require_cmd java
  jar="$REPO_ROOT/artifacts/newest/server.jar"
  [[ -f "$jar" ]] || die "missing artifacts/newest/server.jar; run 'sbt buildServerDev' first"
  load_env server.env
  SERVER_VERSION="local-$(git_version)"
  export SERVER_PORT=9000 SERVER_HOSTNAME=localhost SERVER_VERSION
  export SERVER_ALLOWED_ORIGINS="http://localhost:$port,http://127.0.0.1:$port"
  warn "the local backend uses $SQL_DATABASE on $SQL_HOST from server.env and sends real mail"
  # Play binds to all interfaces; nothing secret is served there, only the API.
  java -jar "$jar" &
  backend=$!
  on_exit "kill $backend 2>/dev/null"
  log "backend: http://localhost:9000/health"
fi

log "pages: http://localhost:$port/homepage/  (Ctrl-C stops everything)"
cd "$REPO_ROOT"
npx --yes http-server . -a 127.0.0.1 -p "$port" -c-1 --silent
