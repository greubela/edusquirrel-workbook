function imageDimensions(bytes){
 if(bytes.subarray(0,8).equals(Buffer.from([137,80,78,71,13,10,26,10])))return {width:bytes.readUInt32BE(16),height:bytes.readUInt32BE(20)};
 let offset=2;
 while(offset<bytes.length){
  if(bytes[offset++]!==0xff)throw new Error('Invalid JPEG marker');
  let marker=bytes[offset++];while(marker===0xff)marker=bytes[offset++];
  if([0xc0,0xc1,0xc2].includes(marker))return {width:bytes.readUInt16BE(offset+5),height:bytes.readUInt16BE(offset+3)};
  offset+=bytes.readUInt16BE(offset);
 }
 throw new Error('JPEG dimensions unavailable');
}
